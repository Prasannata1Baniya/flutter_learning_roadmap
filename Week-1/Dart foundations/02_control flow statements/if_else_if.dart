void main(){
  //if/else if statement

    int marks =100;
    if(marks >= 90){
      print("Grade A+");
    }
    else if(marks >= 80){
      print("Grade A");
    }
    else if(marks >= 70){
      print("Grade B");
    }
    else if(marks >= 60){
      print("Grade C");
    }
    else if(marks>=50){
      print("Grade D");
    }
    else{
      print("Fail");
    }
}